import assert from 'node:assert/strict';
import test from 'node:test';
import { createHash } from 'node:crypto';
import { GEMMA4_PROJECTOR_RECIPE as recipe } from '../../src/peercompute/artifacts/gemma4ProjectorRecipe.js';
import { createGemma4ProjectorSource, gemma4Bfloat16ToFloat16, gemma4ProjectorSourceIndex }
  from '../../src/peercompute/artifacts/gemma4ProjectorSource.js';

const first = recipe.tensors[0], chunkBytes = 1024 ** 2;
function rangeResponse(start, size, bytes = new Uint8Array(size), extraHeaders = {}) {
  return new Response(bytes, { status: 206, headers: {
    'Content-Range': `bytes ${start}-${start + size - 1}/${recipe.source.size}`,
    'Content-Length': String(size), ...extraHeaders,
  } });
}
async function consume(options) {
  for await (const bytes of createGemma4ProjectorSource(options)) assert.ok(bytes.length <= chunkBytes);
}

test('BF16 conversion matches independent PyTorch CPU half conversion for every bit encoding', () => {
  // Generated by torch 2.15.0+cpu: arange(65536).to(uint16).view(bfloat16).to(float16).
  // Includes both signs, nearest-even underflow ties, infinities and NaN payloads.
  const bytes = Buffer.alloc(65536 * 2);
  for (let bits = 0; bits < 65536; bits++) bytes.writeUInt16LE(gemma4Bfloat16ToFloat16(bits), bits * 2);
  assert.equal(createHash('sha256').update(bytes).digest('hex'),
    '77a6185483423cf9e70d8767f91c87e2f3abad239057a84b09afaaef7ae0c2a7');
});

test('image transforms map each independent channel and position axis without changing row membership', () => {
  for (const row of [0, 1, 3839]) {
    const mapped = new Set();
    for (let channel = 0; channel < 3; channel++) {
      for (let pixel = 0; pixel < 48 * 48; pixel++) {
        const output = row * 6912 + channel * 2304 + pixel;
        const input = gemma4ProjectorSourceIndex('patch-chw', output);
        assert.equal(input, row * 6912 + pixel * 3 + channel);
        mapped.add(input);
      }
    }
    assert.equal(mapped.size, 6912);
  }
  for (const axis of [0, 1]) for (const position of [0, 1, 1119]) for (const feature of [0, 3839]) {
    const output = (axis * 1120 + position) * 3840 + feature;
    assert.equal(gemma4ProjectorSourceIndex('position-xy', output), (position * 2 + axis) * 3840 + feature);
  }
  assert.equal(gemma4ProjectorSourceIndex('identity', 9123), 9123);
  assert.throws(() => gemma4ProjectorSourceIndex('custom-js', 0), /unknown trusted/);
});

test('source refuses a server ignoring Range without reading the full checkpoint', async () => {
  let reads = 0, cancellations = 0, requests = 0;
  await assert.rejects(consume({ fetchImpl: async () => {
    requests++;
    return { status: 200, body: {
      getReader() { reads++; throw new Error('Must not read'); },
      cancel() { cancellations++; },
    } };
  } }), /must honor bounded ranges/);
  assert.equal(requests, 1); assert.equal(reads, 0); assert.equal(cancellations, 1);
});

test('source rejects mismatched ranges and declared lengths without retry', async () => {
  for (const headers of [
    { 'Content-Range': `bytes 0-${chunkBytes - 1}/${recipe.source.size}` },
    { 'Content-Range': `bytes ${first.sourceOffset}-${first.sourceOffset + chunkBytes - 1}/*` },
    { 'Content-Length': String(chunkBytes + 1) },
  ]) {
    let calls = 0;
    await assert.rejects(consume({ fetchImpl: async () => {
      calls++; return rangeResponse(first.sourceOffset, chunkBytes, new Uint8Array(chunkBytes), headers);
    } }), /Content-(?:Range|Length) mismatch/);
    assert.equal(calls, 1);
  }
});

test('source retries network/503 failures at the same bounded range and cancellation stops progress', async () => {
  const controller = new AbortController(), reason = new Error('Stop after downloaded range'), requests = [], progress = [];
  await assert.rejects(consume({ signal: controller.signal, fetchImpl: async (url, options) => {
    requests.push({ url, range: options.headers.Range });
    if (requests.length === 1) throw new TypeError('Network changed');
    if (requests.length === 2) return new Response(null, { status: 503 });
    return rangeResponse(first.sourceOffset, chunkBytes);
  }, onProgress(event) { progress.push(event); controller.abort(reason); } }), (error) => error === reason);
  assert.equal(requests.length, 3);
  for (const request of requests) assert.deepEqual(request, {
    url: recipe.source.url, range: `bytes=${first.sourceOffset}-${first.sourceOffset + chunkBytes - 1}`,
  });
  assert.equal(progress.length, 1);
  assert.equal(progress[0].sourceLoaded, chunkBytes);
  assert.equal(progress[0].sourceTotalBytes, 104759808);
  assert.equal(progress[0].loaded, 1888);
});

test('truncated ranges have a finite retry budget', async () => {
  let requests = 0;
  await assert.rejects(consume({ fetchImpl: async () => {
    requests++; return rangeResponse(first.sourceOffset, chunkBytes, new Uint8Array(2));
  } }), (error) => /after 3 attempts/.test(error.message) && /truncated/.test(error.cause.message));
  assert.equal(requests, 3);
});

test('oversized streams fail immediately rather than buffering a full response', async () => {
  let requests = 0;
  await assert.rejects(consume({ fetchImpl: async () => {
    requests++; return rangeResponse(first.sourceOffset, chunkBytes, new Uint8Array(chunkBytes + 1));
  } }), /oversized source range/);
  assert.equal(requests, 1);
});

test('per-tensor hashes prevent conversion of corrupt source bytes', async () => {
  const seen = [];
  await assert.rejects(consume({ fetchImpl: async (url, { headers }) => {
    const [, start, end] = /^bytes=(\d+)-(\d+)$/.exec(headers.Range).map(Number);
    const size = end - start + 1;
    seen.push({ start, size });
    return rangeResponse(start, size);
  } }), /source tensor digest mismatch: model.embed_audio/);
  assert.equal(seen.reduce((sum, item) => sum + item.size, 0), first.sourceBytes);
  assert.equal(seen.every((item) => item.size <= chunkBytes), true);
  assert.equal(seen.at(-1).start + seen.at(-1).size, first.sourceOffset + first.sourceBytes);
});

test('pre-cancellation fetches nothing', async () => {
  const controller = new AbortController(); controller.abort();
  await assert.rejects(consume({ signal: controller.signal, fetchImpl() { assert.fail('Unexpected fetch'); } }), { name: 'AbortError' });
});

test('cancellation interrupts a stalled response reader', { timeout: 1000 }, async () => {
  const controller = new AbortController(), reason = new Error('Cancel stalled reader');
  let readStarted, cancelCalled = false;
  const started = new Promise((resolve) => { readStarted = resolve; });
  const pending = consume({ signal: controller.signal, fetchImpl: async () => ({
    status: 206, headers: new Headers({ 'Content-Range': `bytes ${first.sourceOffset}-${first.sourceOffset + chunkBytes - 1}/${recipe.source.size}` }),
    body: { getReader: () => ({ read() { readStarted(); return new Promise(() => {}); },
      cancel() { cancelCalled = true; return new Promise(() => {}); }, releaseLock() {} }) },
  }) });
  const rejected = assert.rejects(pending, (error) => error === reason);
  await started; controller.abort(reason); await rejected;
  assert.equal(cancelCalled, true);
});
