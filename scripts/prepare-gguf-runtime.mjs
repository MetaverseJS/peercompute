import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import path from 'node:path';
import { build, version as esbuildVersion } from 'esbuild';

const require = createRequire(import.meta.url);
const packageRoot = path.dirname(require.resolve('@wllama/wllama/package.json'));
const pinned = {
  'src/wasm/wllama.js': '1cdbb0231eeda4226d56756a6a98815a941b41445c7916dc9c154c0b737cacec',
  'src/glue/glue.ts': 'beebca7be2c9c96d308f39c2b98a74908ac170e7af106ab0c2a9ad12a5f2af3f',
  'src/glue/messages.ts': '2af925b377f67e0fcd29a70f13dcdbb2d3170b331f35f8559fb58119f243de9c',
  'esm/wasm/wllama.wasm': '551f13439366eff11e057b1b91fe46a7fdac29d56d67372d4c5f19a549dfe70c',
};
if (JSON.parse(await readFile(path.join(packageRoot, 'package.json'))).version !== '3.8.1') {
  throw new Error('GGUF adapter requires exact @wllama/wllama 3.8.1');
}
if (esbuildVersion !== '0.25.12') throw new Error('GGUF adapter generation requires exact esbuild 0.25.12');
for (const [file, expected] of Object.entries(pinned)) {
  const bytes = await readFile(path.join(packageRoot, file));
  if (createHash('sha256').update(bytes).digest('hex') !== expected) throw new Error(`Untrusted Wllama input: ${file}`);
}
const license = await readFile(path.join(packageRoot, 'LICENCE'), 'utf8');
const banner = `/* Generated by PeerCompute from @wllama/wllama 3.8.1.\n${license.replaceAll('*/', '* /')}\n*/\n`;
let source = await readFile(path.join(packageRoot, 'src/wasm/wllama.js'), 'utf8');
const declaration = 'var Module=typeof Module!="undefined"?Module:{};';
if (!source.startsWith(declaration)) throw new Error('Unexpected Wllama module initializer');
source = source.slice(declaration.length);
const deviceHook = 'WebGPU.Internals.jsObjectInsert(devicePtr,device);';
if (source.split(deviceHook).length !== 3) throw new Error('Unexpected Wllama device registration sites');
source = source.replaceAll(deviceHook, `${deviceHook}Module.peercomputeOnDevice?.(device);`);
// Local bindings preserve the owning ComputeManager worker's global message handler.
// Any latent pthread spawn fails before an unmanaged child worker can be created.
const generated = `${banner}export function initializeWllamaModule(Module, _wllama_js_file_read) {\n`
  + `const Worker = class { constructor() { throw new Error('Nested GGUF workers are prohibited'); } };\n`
  + `let onmessage;\n${source}\nreturn Module;\n}\n`;
await writeFile(path.join(packageRoot, 'peercompute-engine.js'), generated);
await build({ entryPoints: [path.join(packageRoot, 'src/glue/glue.ts')], bundle: true,
  platform: 'browser', format: 'esm', target: 'esnext', legalComments: 'inline',
  banner: { js: banner }, outfile: path.join(packageRoot, 'peercompute-glue.js'), logLevel: 'silent' });
await writeFile(path.join(packageRoot, 'peercompute-runtime-provenance.json'), JSON.stringify({
  package: '@wllama/wllama', version: '3.8.1', pinned,
  generator: { esbuild: esbuildVersion },
  llamaCppRevision: '46ca246de9bb1c35269722a6240d37d9dfd79cad',
  changes: ['same-worker static factory', 'lexical nested-worker prohibition', 'owned device observation'],
}, null, 2));
console.log('Prepared pinned same-worker GGUF runtime in ignored node_modules/@wllama/wllama');
